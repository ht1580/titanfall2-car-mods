    def _log(self, text: str) -> None:
        self.events.put(("log", text))

    def _job(self, title: str, function, on_success=None) -> None:
        def worker():
            self.events.put(("busy", True))
            self._log(f"\n[{title}]")
            try:
                result = function()
                if result is not None:
                    self._log(json.dumps(result, ensure_ascii=False, indent=2) if isinstance(result, (dict, list)) else str(result))
                self.events.put(("done", (title, result, on_success)))
            except Exception:
                self._log(traceback.format_exc())
                self.events.put(("error", title))
            finally:
                self.events.put(("busy", False))
        threading.Thread(target=worker, daemon=True).start()

    def _drain_events(self) -> None:
        try:
            while True:
                kind, payload = self.events.get_nowait()
                if kind == "log":
                    self.log_text.configure(state="normal")
                    self.log_text.insert("end", str(payload) + "\n")
                    self.log_text.see("end")
                    self.log_text.configure(state="disabled")
                elif kind == "busy":
                    self.configure(cursor="wait" if payload else "")
                elif kind == "done":
                    title, result, callback = payload
                    if callback:
                        callback(result)
                    messagebox.showinfo("完成", f"{title} 已完成")
                elif kind == "error":
                    messagebox.showerror("失败", f"{payload} 失败，请查看运行日志")
        except queue.Empty:
            pass
        self.after(80, self._drain_events)


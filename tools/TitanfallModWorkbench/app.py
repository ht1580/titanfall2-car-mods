class Workbench(tk.Tk):
    def __init__(self) -> None:
        super().__init__()
        self.title(f"Titanfall Mod Workbench {core.APP_VERSION}")
        self.geometry("1220x840")
        self.minsize(980, 700)
        self.option_add("*Font", ("Microsoft YaHei UI", 9))
